interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "en",
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLangState] = useState<LanguageCode>("en");

  useEffect(() => {
    try {
      const savedUser = localStorage.getItem("ipsakti_user");
      if (savedUser) {
        const u = JSON.parse(savedUser);
        if (u.language && TRANSLATIONS[u.language as LanguageCode]) {
          setLangState(u.language as LanguageCode);
          return;
        }
      }
      const savedLang = localStorage.getItem("ipsakti_lang") as LanguageCode;
      if (savedLang && TRANSLATIONS[savedLang]) {
        setLangState(savedLang);
      }
    } catch {
      // ignore
    }
  }, []);

  const setLanguage = (newLang: LanguageCode) => {
    setLangState(newLang);
    try {
      localStorage.setItem("ipsakti_lang", newLang);
      const savedUser = localStorage.getItem("ipsakti_user");
      if (savedUser) {
        const u = JSON.parse(savedUser);
        u.language = newLang;
        localStorage.setItem("ipsakti_user", JSON.stringify(u));
      }
      window.dispatchEvent(new CustomEvent("languagechange", { detail: newLang }));
    } catch {
      // ignore
    }
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = TRANSLATIONS.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
